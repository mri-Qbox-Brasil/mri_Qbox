local UTILITY = { [`WEAPON_FIREEXTINGUISHER`] = true, [`WEAPON_PETROLCAN`] = true }

local function setPickups(allowed)
    for _, name in ipairs(PICKUPS) do
        ToggleUsePickupsForPlayer(cache.playerId, joaat(name), allowed)
    end
end

local active

-- the pistol whip block needs every frame, so only while a firearm is in hand
local function guard()
    local token = {}
    active = token
    CreateThread(function()
        while active == token do
            if IsPedArmed(cache.ped, 6) then
                DisableControlAction(1, 140, true)
                DisableControlAction(1, 141, true)
                DisableControlAction(1, 142, true)
            end
            Wait(0)
        end
    end)
end

local function onWeapon(weapon)
    active = nil
    if not weapon or not Mri.enabled('gtaweapons') then return end
    local cfg = Mri.cfg('gtaweapons')
    if UTILITY[weapon] then SetPedInfiniteAmmo(cache.ped, cfg.infiniteUtility == true, weapon) end
    if cfg.noPistolWhip then guard() end
end

lib.onCache('weapon', onWeapon)

Mri.lifecycle('gtaweapons', function(cfg)
    if cfg.blockPickups then setPickups(false) end
    onWeapon(cache.weapon)
end, function()
    active = nil
    setPickups(true)
    for weapon in pairs(UTILITY) do SetPedInfiniteAmmo(cache.ped, false, weapon) end
end)

-- the event comes before the ped exists, so it waits a moment and takes the closest one
AddEventHandler('populationPedCreating', function(x, y, z)
    if not Mri.enabled('gtaweapons') or not Mri.cfg('gtaweapons').noNpcDrops then return end
    Wait(500)
    local _, ped = GetClosestPed(x, y, z, 1.0)
    SetPedDropsWeaponsWhenDead(ped, false)
end)
